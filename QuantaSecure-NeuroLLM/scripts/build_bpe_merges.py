"""Regenerate the hard-coded BPE merge table from the public corpus.

Usage:  python scripts/build_bpe_merges.py

Writes ``quantasecure_neurollm/llm/bpe_merges.py``.  The test-suite checks that
the committed table equals a fresh deterministic training run, so the
"hard-coded vocabulary" can always be audited against its source text.
"""

from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from quantasecure_neurollm.corpus import corpus_digest, tokenizer_training_texts  # noqa: E402
from quantasecure_neurollm.llm.tokenizer import train_bpe  # noqa: E402

N_MERGES = 320


def main() -> None:
    merges = train_bpe(tokenizer_training_texts(), N_MERGES)
    lines = [
        '"""Hard-coded BPE merge table (generated by scripts/build_bpe_merges.py -- do not edit by hand)."""',
        "",
        f"N_MERGES_REQUESTED = {N_MERGES}",
        f'CORPUS_SHA3 = "{corpus_digest().hex()}"',
        "",
        "MERGES: tuple[tuple[int, int], ...] = (",
    ]
    for i in range(0, len(merges), 8):
        lines.append("    " + " ".join(f"({a}, {b})," for a, b in merges[i : i + 8]))
    lines.append(")")
    out = ROOT / "quantasecure_neurollm" / "llm" / "bpe_merges.py"
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {len(merges)} merges to {out}")


if __name__ == "__main__":
    main()
